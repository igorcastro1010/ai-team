import { expect, test } from "@playwright/test";

test("estúdio edita timeline, salva rascunho e mantém limites", async ({ page }) => {
  await page.goto("/login");
  await page.getByLabel("Usuário", { exact: true }).fill("e2e");
  await page.getByLabel("Senha", { exact: true }).fill("somente-teste-e2e-8493");
  await page.getByRole("button", { name: "Entrar no workspace" }).click();
  await expect(page.getByRole("heading", { name: "Sua sala de operações." })).toBeVisible();
  const response = await page.request.post("/api/control/projects", { headers: { origin: "http://localhost:3100" }, data: { name: `Estúdio ${Date.now()}` } });
  expect(response.status()).toBe(201);
  const project = (await response.json()).id;
  await page.goto("/videos");
  await page.getByRole("button", { name: "Modo avançado", exact: true }).click();
  await page.getByLabel("Projeto dos vídeos").selectOption(project);
  await page.getByLabel("Título do vídeo").fill("Minha timeline");
  await page.getByLabel("Texto da cena 1", { exact: true }).fill("Abertura original");
  await page.getByRole("button", { name: "Duplicar cena" }).click();
  await expect(page.getByRole("button", { name: "Selecionar cena 2" })).toBeVisible();
  await page.getByLabel("Texto da cena 2", { exact: true }).fill("Segunda parte");
  await page.getByRole("button", { name: "Mover cena para cima" }).click();
  await expect(page.getByLabel("Texto da cena 1", { exact: true })).toHaveValue("Segunda parte");
  await expect(page.getByText("Rascunho salvo", { exact: true })).toBeVisible();
  await page.reload();
  await page.getByRole("button", { name: "Modo avançado", exact: true }).click();
  await page.getByLabel("Projeto dos vídeos").selectOption(project);
  await expect(page.getByLabel("Título do vídeo")).toHaveValue("Minha timeline");
  await page.getByRole("button", { name: "Selecionar cena 2" }).click();
  await expect(page.getByLabel("Texto da cena 2", { exact: true })).toHaveValue("Abertura original");
  await page.getByRole("button", { name: "Remover cena 2" }).click();
  await expect(page.getByRole("button", { name: "Remover cena 1" })).toBeDisabled();
  await expect(page.getByText("Rascunho salvo", { exact: true })).toBeVisible();
  const draftUrl = `/api/control/video-studio/${project}/draft`;
  const saved = await (await page.request.get(draftUrl)).json();
  const remote = { ...saved.document, title: "Alterado em outra janela" };
  const changed = await page.request.put(draftUrl, { headers: { origin: "http://localhost:3100" }, data: { revision: saved.revision, document: remote } });
  expect(changed.status()).toBe(200);
  await page.getByLabel("Texto da cena 1", { exact: true }).fill("Meu texto local preservado");
  await expect(page.getByText("Este rascunho mudou em outra janela.")).toBeVisible();
  await expect(page.getByLabel("Texto da cena 1", { exact: true })).toHaveValue("Meu texto local preservado");
  await page.getByRole("button", { name: "Recarregar versão salva" }).click();
  await expect(page.getByLabel("Título do vídeo")).toHaveValue("Alterado em outra janela");
  await page.getByLabel("Nome do seu template").fill("Meu modelo reutilizável");
  await page.getByRole("button", { name: "Salvar como template" }).click();
  await expect(page.getByRole("button", { name: /Meu modelo reutilizável/ })).toBeVisible();
  await page.getByRole("button", { name: /Reels de divulgação 3 cenas/ }).click();
  await expect(page.getByRole("button", { name: "Selecionar cena 2" })).toBeVisible();
  await expect(page.getByText("Nenhum vídeo neste projeto.")).toBeVisible();
  await page.getByLabel("Importar mídia local").setInputFiles({ name: "imagem-local.png", mimeType: "image/png", buffer: Buffer.from("iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jGv8AAAAASUVORK5CYII=", "base64") });
  await expect(page.getByRole("button", { name: "Usar na cena 1" })).toBeVisible();
  await page.getByRole("button", { name: "Usar na cena 1" }).click();
  await expect(page.getByRole("img", { name: "Mídia da cena" })).toBeVisible();
  await page.getByRole("button", { name: /Meu modelo reutilizável/ }).click();
  for (let index = 0; index < 5; index++) await page.getByRole("button", { name: "Adicionar cena", exact: true }).click();
  await expect(page.getByRole("button", { name: "Selecionar cena 6" })).toBeVisible();
  await expect(page.getByRole("button", { name: "Adicionar cena", exact: true })).toBeDisabled();
  await expect(page.getByRole("button", { name: "Duplicar cena", exact: true })).toBeDisabled();
  await page.getByRole("button", { name: "Selecionar cena 1" }).click();
  await page.screenshot({ path: "../../.data/video-studio-desktop.png", fullPage: true });
  await page.route(`**/api/control/videos?project_id=${project}`, route => route.fulfill({ json: { renderer: { available: true, reason: "", supports_1080p: false }, items: [{ id: "worker-progress", title: "Progresso observado", format: "vertical", scenes: [{ text: "Cena", duration: 5 }], digest: "digest", status: "rendering", error: "", progress: 37, phase: "Renderizando" }] } }));
  await page.getByRole("button", { name: "Atualizar vídeos" }).click();
  await expect(page.getByRole("progressbar", { name: "Progresso de Progresso observado" })).toHaveAttribute("value", "37");
  await expect(page.getByText("Renderizando · 37%", { exact: true })).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy();
  await page.screenshot({ path: "../../.data/video-studio-mobile.png", fullPage: true });
});
